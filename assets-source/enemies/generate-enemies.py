class Art:
    def __init__(self, w, h): self.w=w; self.h=h; self.parts=[]
    def rect(self,x,y,w,h,c): self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{c}"/>')
    def poly(self,pts,c): self.parts.append('<polygon points="'+ ' '.join(f'{x},{y}' for x,y in pts)+f'" fill="{c}"/>')
    def save(self,p): p.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" viewBox="0 0 {self.w} {self.h}" shape-rendering="crispEdges">'+''.join(self.parts)+'</svg>\n')
